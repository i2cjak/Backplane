import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {encode} from './ios_test_cbor';
import {cbor,plain} from '../../src/web/wire.js';
const [bridge,fixture]=process.argv.slice(2);
const b:any={console};vm.runInNewContext(readFileSync(bridge,'utf8'),b);
const f:any={console};vm.runInNewContext(readFileSync(fixture,'utf8'),f);
const B=b.Backplane, server=f.RecentFixture;
const metadata=JSON.parse(B.headerKeys());
const un=(cmd:any)=>plain(cbor(new Uint8Array(Buffer.from(cmd.data,'base64')),metadata.keys,metadata.words));
const receive=(value:any)=>{const a:number[]=[];encode(value,a);return JSON.parse(B.recv('box:3787',Buffer.from(a).toString('base64'),false,false));};
const screenRequest=(out:any)=>out.cmds.map((c:any)=>c.type==='send'?un(c):null).find((r:any)=>r?.m==='mobile.screen');
const answer=(r:any)=>receive({t:'reply',id:r.id,ok:true,result:JSON.parse(server.render(JSON.stringify(r.p)))});
B.start('phone','{}');B.hubs(['box:3787']);B.online('box:3787',true,true);
let out=receive({t:'mobile',generation:'g1'});
assert.equal(out.screen,null);
assert.equal(out.sync[0].phase,'recent');
const initial=screenRequest(out);assert.ok(initial);
out=answer(initial);
assert.ok(out.screen.projects.length,'authoritative recent presentation before any log replay');
assert.equal(out.cmds.map((c:any)=>c.type==='send'?un(c)?.m:'').filter((m:any)=>m==='mobile.history').length,1);
assert.equal(JSON.parse(B.resume('box:3787')).since,'0','presentation never advances canonical cursor');
out=answer(screenRequest(JSON.parse(B.act('select','box:3787|t2'))));
assert.equal(out.screen.thread.id,'box:3787|t2');
assert.equal(out.screen.thread.readingSeen,'raw-message','reading holds the raw event ID, not a rendered paragraph/fold ID');
assert.deepEqual(Array.from(out.screen.thread.permissions.choices,(c:any)=>c.value),['approval-required','auto-accept-edits','auto','full-access'],'authoritative server preview preserves exact permission protocol values');
const permission = screenRequest(JSON.parse(B.act('thread-permissions','auto-accept-edits')));
assert.ok(permission, 'permission tap requests an authoritative recent action');
const permissionOut = answer(permission);
const permissionRPC = permissionOut.cmds.filter((c:any)=>c.type==='send').map(un).find((r:any)=>r.m==='thread.modes');
assert.ok(permissionRPC, 'recent permission action emits the ordinary mutation RPC');
assert.equal(permissionRPC.p.thread,'t2');
assert.equal(permissionRPC.p.runtime,'auto-accept-edits');
B.quiet('draft','captured message');
const send=screenRequest(JSON.parse(B.act('send','')));assert.ok(send);
B.quiet('draft','new unsent draft');
out=answer(send);
const sends=out.cmds.filter((c:any)=>c.type==='send').map(un).filter((o:any)=>o.m==='turn.start');
assert.equal(sends.length,1);
assert.equal(sends[0].p.text,'captured message');
assert.equal(out.cmds.filter((c:any)=>c.type==='keep').at(-1).text,'new unsent draft','old clear cannot overwrite a newer saved draft');
const refresh=screenRequest(receive({t:'reply',id:sends[0].id,ok:true}));
assert.ok(refresh,'durable mutation acknowledgement refreshes the authoritative recent screen');
assert.equal(answer(send).cmds.filter((c:any)=>c.type==='send').map(un).filter((o:any)=>o.m==='turn.start').length,0,'duplicate presentation reply never sends twice');
const pendingMode=screenRequest(JSON.parse(B.act('thread-permissions','approval-required')));
assert.ok(pendingMode,'permission action preempts outstanding refresh');
out=receive({t:'log',origin:'canonical-origin',more:true,info:{},items:[{$:'ProjectCreated',id:'p2',title:'Box',root:'/box',at:50}]});
assert.equal(out.screen,null,'old history never replaces recent presentation');
out=receive({t:'changes',boot:false,items:[{$:'ThreadCreated',id:'t2',project:'p2',title:'Two',env:'local',branch:'',worktree:'',provider:'claude',model:'',at:100}]});
assert.equal(out.sync.at(-1).phase,'live');
assert.equal(out.screen.thread.id,'box:3787|t2');
assert.equal(out.screen.thread.draft,'new unsent draft');
const handedOffMode=out.cmds.filter((c:any)=>c.type==='send').map(un).filter((o:any)=>o.m==='thread.modes');
assert.equal(handedOffMode.length,1,'completed canonical history immediately executes pending permission action');
assert.equal(handedOffMode[0].p.runtime,'approval-required');
assert.equal(answer(pendingMode).cmds.filter((c:any)=>c.type==='send').map(un).filter((o:any)=>o.m==='thread.modes').length,0,'late presentation cannot issue permission twice');
assert.equal(answer(refresh).cmds.filter((c:any)=>c.type==='send').map(un).filter((o:any)=>o.m==='turn.start').length,0,'obsolete refresh cannot repeat send');
out=receive({t:'changes',items:[{$:'ModesSet',id:'t2',runtime:'approval-required',interaction:'default',model:'',at:901}]});
assert.equal(out.screen.thread.permissions.current,'Permissions: Approval required','new canonical events remain visible after handoff');
assert.equal(JSON.parse(B.resume('box:3787')).origin,'canonical-origin');
assert.equal(JSON.parse(B.resume('box:3787')).since,'3');
console.log('PASS real bridge + real Bend session: recent-first, ordinary exact send, atomic draft clear, duplicate replies, ordered history and cursor-preserving handoff');
